import fs from 'node:fs/promises';
import {FileBlob,SpreadsheetFile} from '@oai/artifact-tool';
const dir='C:/Projects/BOAT/outputs/jan1285-sample';
const w=await SpreadsheetFile.importXlsx(await FileBlob.load(dir+'/input.xlsx'));
const s=w.worksheets.getItem('JAN 1285');
console.log((await w.inspect({kind:'region',sheetId:'JAN 1285',range:'F2:R3',maxChars:2000,tableMaxCols:13})).ndjson);
await fs.writeFile(dir+'/before.png',new Uint8Array(await (await w.render({sheetName:'JAN 1285',range:'F1:L5',scale:1.5})).arrayBuffer()));
if(process.argv.includes('--inspect')) process.exit(0);
const mapping=JSON.parse(await fs.readFile(dir+'/mapping.json','utf8'));
const codes={'Academic Programmes':1,'Administrative Expenses':2,'Kitchen Expenses':9,'Plant Maintenance':15,'Sanitation & Hygiene':16,'Staff Welfare':18,'Stationery':19,'Vehicle Running Costs':24};
const headers=s.getRange('F2:R2').values[0];
const changes=headers.map(h=>{const m=mapping.find(r=>String(r[0]).trim().toUpperCase()===h.trim().toUpperCase());if(!m)throw Error(h);return h+'\nVote '+codes[m[1]]+' — '+m[1];});
s.getRange('F2:R2').values=[changes];
s.getRange('F2:R2').format.wrapText=true;
s.getRange('A2:S2').format.rowHeight=115;
w.recalculate();
console.log((await w.inspect({kind:'region',sheetId:'JAN 1285',range:'F2:R2',maxChars:3000,tableMaxCols:13})).ndjson);
await fs.writeFile(dir+'/after.png',new Uint8Array(await (await w.render({sheetName:'JAN 1285',range:'F1:R5',scale:1.5})).arrayBuffer()));
await (await SpreadsheetFile.exportXlsx(w)).save(dir+'/authored.xlsx');
await fs.writeFile(dir+'/changes.json',JSON.stringify(changes));
